r"""Candidate hands-back detector `v3`, frozen before its validation sample.

v2 (`detector_v2.py`) reads 73.7% precision and 87.5% recall on the fresh
80-response batch it was frozen against. Its two error classes are systematic
and #153 names them; this file addresses exactly those two and nothing else.

  - **Every false positive (5 of 5) is a self-resolved fork.** The answer poses
    a question and answers it in the same breath: F15 asks "do you have (or can
    you add) an idempotency key on the charge call?" and continues "If yes, this
    is a straightforward reconcile-then-retry job. If the processor..." The
    reader is not blocked, so nothing was handed back.
  - **Both false negatives are hand-backs with no question mark.** F78 opens
    "The fork I can't resolve without knowing your setup:" and branches; F06
    ends "Which database are you on, and roughly how many products — that
    decides which of the two to actually spec out." with a period.

Designed after seeing which responses v2 got wrong, so **any figure measured on
batches 1 and 2 is in-sample and is not an estimate.** v2 read 93.1% in-sample
against 73.7% fresh, a 19-point overstatement, which is what designing on the
sample you then score on produces.

This file is committed BEFORE the third sample is drawn or labelled, so the
out-of-sample figure will be measured against a detector that could not have
been adjusted to suit it. The third sample must be disjoint from both existing
batches. Do not edit this file to improve a result; write a v4.
"""
import re

# First-person offers to do more work. Carried unchanged from v2: these are not
# hand-backs, they are the answer volunteering further effort after resolving.
OFFER = re.compile(r"\b(want me to|shall i|should i (sketch|write|draft|map)|"
                   r"would you like me to|do you want me to)\b", re.I)

# v1, for v2's fallback below.
LINE_QUESTION = re.compile(r"^[^\n]*\?\s*$", re.M)

# --- new in v3 -----------------------------------------------------------

# A question the answer resolves itself, in the text following the question
# mark. Either branch-by-branch ("If yes, ... If it's horizontally scaled ...")
# or by simply picking ("Recommendation: start with Postgres full-text search").
# Only the text AFTER the last `?` in the paragraph counts: a recommendation
# stated before the question does not resolve it.
SELF_RESOLVED = re.compile(
    r"\bif (?:yes|no|not|so|it'?s|you'?re|you (?:are|do|don'?t|have|need)|"
    r"the |they |that )"
    r"|\beither way\b|\bin both cases\b|\bin either case\b"
    r"|\brecommendation\b|\bi'?d (?:start|go|default|pick|use)\b"
    r"|\bdefault to\b|\bstart with\b",
    re.I)

# A hand-back that never uses a question mark. Two shapes, both from the two
# false negatives and kept narrow:
#
#   (a) the answer says outright that it cannot resolve something without
#       information the user holds;
#   (b) a wh-question addressed to the reader that ends in a period or a dash.
#       Bounded to openers naming the reader's own situation, because a bare
#       "what happens next" is exposition rather than a hand-back.
CANNOT_RESOLVE = re.compile(
    r"\b(?:can'?t|cannot|unable to) (?:resolve|say|tell|decide|pick|choose|"
    r"answer|call)\b[^.\n]{0,60}\bwithout\b"
    r"|\bwithout knowing (?:your|what|which|how)\b"
    r"|\bthe fork i can'?t resolve\b"
    r"|\bdepends on (?:your|what|which)\b[^.\n]{0,60}\bi (?:don'?t|can'?t)\b",
    re.I)
# The wh-word must OPEN the line. A first draft allowed it anywhere, which
# fired on any closing line containing "what" and "you" - "Left out: ... and
# what 'processing' looks like in the UI - those are the next layer down once
# you pick sync vs async." - and cost 11 false positives on batch 2 alone. A
# hand-back asks; a sentence that merely mentions "what" reports.
WH_STATEMENT = re.compile(
    r"^\s*(?:[-*]\s*)?(?:\*\*)?"
    r"(?:which|what|how many|how much|how big|whose)\b"
    # No colon: a wh-phrase followed by one is a label, not a question -
    # "**What you cache**: raw query rows vs. ..." and "What I'm leaving out:
    # ..." both open a line with a wh-word and both report rather than ask.
    r"[^\n?:]*\byou\b[^\n?:]*[.\u2014\u2013]\s*$",
    re.M | re.I)


def _self_resolved(para):
    """True when the paragraph answers its own question after asking it."""
    tail = para.rsplit("?", 1)[-1]
    return bool(SELF_RESOLVED.search(tail))


def asks_back(text):
    """True when the answer hands a decision back to the user.

    v2's rule, minus questions the answer resolves itself, plus two shapes of
    hand-back that carry no question mark.
    """
    paras = [p for p in text.strip().split("\n\n") if p.strip()]
    closing = paras[-2:]

    # v3(b): an explicit unresolved dependency, anywhere in the response.
    if CANNOT_RESOLVE.search(text):
        return True
    # v3(b): a wh-question to the reader that ends without a question mark,
    # in the closing paragraphs where a hand-back lives.
    for para in closing:
        if WH_STATEMENT.search(para) and not OFFER.search(para):
            return True

    # v2, plus v3(a): a resolved question is not a hand-back.
    for para in closing:
        if "?" in para and not OFFER.search(para) and not _self_resolved(para):
            return True
    if LINE_QUESTION.search(text) and not OFFER.search(text):
        for para in closing:
            if "?" in para and _self_resolved(para):
                return False
        return True
    return False
